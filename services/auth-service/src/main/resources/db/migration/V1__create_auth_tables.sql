-- ---------------------------------------------------------------------
-- app_user: one row per person who can log in.
-- (The name is "app_user" because "user" is a reserved word in SQL.)
-- ---------------------------------------------------------------------
CREATE TABLE app_user (
    -- BIGINT = big whole number. IDENTITY = the database counts 1, 2, 3...
    id        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username  VARCHAR(255) NOT NULL,
    -- We store a BCrypt hash (scrambled password), never the real password.
    password  VARCHAR(255) NOT NULL,
    role      VARCHAR(255),
    -- UNIQUE = two users cannot have the same username.
    CONSTRAINT uk_app_user_username UNIQUE (username)
);

-- ---------------------------------------------------------------------
-- auth_refresh_token: the long-life token that gets a new short token.
-- ---------------------------------------------------------------------
CREATE TABLE auth_refresh_token (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    token       VARCHAR(200) NOT NULL,
    user_id     BIGINT       NOT NULL,
    -- TIMESTAMP WITH TIME ZONE = date and time that knows its time zone.
    expires_at  TIMESTAMP WITH TIME ZONE NOT NULL,
    revoked     BOOLEAN      NOT NULL,
    created_at  TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uk_auth_refresh_token_token UNIQUE (token),
    -- FOREIGN KEY = this column must point to a real user.
    -- ON DELETE CASCADE = when a user is deleted, delete their tokens too.
    -- (The old Hibernate-made table did NOT have this, so deleting a user
    --  who had logged in could fail. We fixed that here.)
    CONSTRAINT fk_auth_refresh_token_user
        FOREIGN KEY (user_id) REFERENCES app_user (id) ON DELETE CASCADE
);

-- Indexes make searches fast, like the index at the back of a book.
CREATE INDEX idx_auth_refresh_token_user_id    ON auth_refresh_token (user_id);
CREATE INDEX idx_auth_refresh_token_expires_at ON auth_refresh_token (expires_at);

-- ---------------------------------------------------------------------
-- security_audit_log: who did what (login, logout, create user...).
-- ---------------------------------------------------------------------
CREATE TABLE security_audit_log (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username    VARCHAR(120) NOT NULL,
    action      VARCHAR(120) NOT NULL,
    details     VARCHAR(4000),
    created_at  TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE INDEX idx_security_audit_log_created_at ON security_audit_log (created_at);

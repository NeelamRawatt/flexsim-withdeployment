-- =====================================================================
-- V1__create_file_tables.sql   (file-service, database: file_db)
-- Flyway runs this file ONE time. Never edit it after it has run.
-- To change something later, add V2__something.sql.
--
-- 3 tables:
--   uploaded_file = the DETAILS of each file (small rows, fast to list)
--   file_content  = the BYTES of each file (only while we store in PostgreSQL;
--                   later Azure Blob Storage takes over this job)
--   outbox_event  = Kafka messages waiting to be sent (same as experiment-service)
-- =====================================================================

CREATE TABLE uploaded_file (
    id                   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    -- The experiment (lives in experiment_db). NO foreign key: other database.
    experiment_id        BIGINT       NOT NULL,
    -- INFEED or ZONE_RESOURCE
    file_category        VARCHAR(30)  NOT NULL,
    file_name            VARCHAR(255) NOT NULL,
    file_extension       VARCHAR(20),
    content_type         VARCHAR(100),
    size_bytes           BIGINT       NOT NULL,
    -- Fingerprint of the content (64 hex characters)
    sha256               VARCHAR(64)  NOT NULL,
    -- DATABASE now, AZURE_BLOB later
    storage_type         VARCHAR(20)  NOT NULL,
    -- Address of the content inside the storage
    storage_key          VARCHAR(255) NOT NULL,
    upload_date          DATE,
    uploaded_at          TIMESTAMP(6) NOT NULL,
    uploaded_by          VARCHAR(255) NOT NULL,
    uploaded_by_user_id  BIGINT,

    CONSTRAINT uk_uploaded_file_storage_key UNIQUE (storage_key),
    -- ONE file per category per experiment. A new upload REPLACES the old one.
    -- The database itself guarantees it, even if 2 uploads arrive at the same moment.
    CONSTRAINT uk_uploaded_file_experiment_category UNIQUE (experiment_id, file_category)
);

-- The unique rule above also gives a fast index on experiment_id (it is the first column).

CREATE TABLE file_content (
    storage_key  VARCHAR(255) PRIMARY KEY,
    -- BYTEA = raw bytes (the Excel file)
    content      BYTEA        NOT NULL,
    created_at   TIMESTAMP(6) NOT NULL
);

CREATE TABLE outbox_event (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    topic       VARCHAR(255) NOT NULL,
    event_key   VARCHAR(255) NOT NULL,
    payload     TEXT         NOT NULL,
    created_at  TIMESTAMP(6) NOT NULL,
    sent_at     TIMESTAMP(6),
    attempts    INTEGER      NOT NULL DEFAULT 0,
    last_error  VARCHAR(500)
);
CREATE INDEX idx_outbox_event_unsent ON outbox_event (id) WHERE sent_at IS NULL;
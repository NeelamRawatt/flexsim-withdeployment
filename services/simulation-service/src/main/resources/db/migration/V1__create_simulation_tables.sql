-- =====================================================================
-- V1__create_simulation_tables.sql   (simulation-service, database: simulation_db)
-- Flyway runs this file ONE time. Never edit it after it has run.
--
-- 2 tables:
--   simulation_run = one row per run of an experiment (its status and timeline)
--   outbox_event   = Kafka messages waiting to be sent (same as the other services)
-- =====================================================================

CREATE TABLE simulation_run (
    id                    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    -- The experiment (lives in experiment_db). NO foreign key: other database.
    experiment_id         BIGINT       NOT NULL,
    -- QUEUED, RUNNING, COMPLETED, FAILED, CANCELLED
    status                VARCHAR(20)  NOT NULL,
    -- Detail inside RUNNING, as FlexSim reports it (example: LOADING_PARCELS)
    stage                 VARCHAR(50),
    message               VARCHAR(500),
    -- The settings sent to the worker, as JSON text
    run_settings          TEXT,
    requested_by          VARCHAR(255) NOT NULL,
    requested_by_user_id  BIGINT,
    queued_at             TIMESTAMP(6) NOT NULL,
    started_at            TIMESTAMP(6),
    finished_at           TIMESTAMP(6),
    updated_at            TIMESTAMP(6) NOT NULL,
    -- Optimistic locking counter (see SimulationRun.java)
    version               BIGINT       NOT NULL DEFAULT 0,

    CONSTRAINT ck_simulation_run_status
        CHECK (status IN ('QUEUED', 'RUNNING', 'COMPLETED', 'FAILED', 'CANCELLED'))
);

-- Fast "all runs of experiment 1006, newest first"
CREATE INDEX idx_simulation_run_experiment ON simulation_run (experiment_id, queued_at DESC);

-- RULE: only ONE active run (QUEUED or RUNNING) per experiment at a time.
-- If the user double-clicks "Run", the database itself refuses the second one,
-- even if both clicks arrive at the same moment. (A "partial unique index".)
CREATE UNIQUE INDEX uk_simulation_run_one_active_per_experiment
    ON simulation_run (experiment_id)
    WHERE status IN ('QUEUED', 'RUNNING');

CREATE TABLE outbox_event (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    topic       VARCHAR(255) NOT NULL,
    event_key   VARCHAR(255) NOT NULL,
    payload     TEXT         NOT NULL,
    created_at  TIMESTAMP(6) NOT NULL,
    sent_at     TIMESTAMP(6),
    attempts    INTEGER      NOT NULL DEFAULT 0,
    last_error  VARCHAR(500)
);
CREATE INDEX idx_outbox_event_unsent ON outbox_event (id) WHERE sent_at IS NULL;
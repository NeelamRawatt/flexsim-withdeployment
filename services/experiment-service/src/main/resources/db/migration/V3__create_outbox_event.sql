-- =====================================================================
-- V3__create_outbox_event.sql   (experiment-service, database: experiment_db)
--
-- The OUTBOX table = an "outgoing letters box" inside OUR database.
-- When something happens (example: an experiment is deleted), we write
-- the Kafka message here, in the SAME transaction as the change itself.
-- A small background job then sends the rows to Kafka (next step).
--
-- Why: the delete and the message are saved together, or not at all.
-- If Kafka is down, the row just waits here and is sent later.
-- =====================================================================
CREATE TABLE outbox_event (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    -- Kafka topic to send to, example: experiment.deleted
    topic       VARCHAR(255) NOT NULL,
    -- Kafka key, example: '1001' (the experimentId) -> keeps order per experiment
    event_key   VARCHAR(255) NOT NULL,
    -- The message itself, as JSON text
    payload     TEXT         NOT NULL,
    created_at  TIMESTAMP(6) NOT NULL,
    -- NULL = not sent yet. Filled when Kafka has confirmed it.
    sent_at     TIMESTAMP(6),
    -- How many times sending failed, and the last error (for support)
    attempts    INTEGER      NOT NULL DEFAULT 0,
    last_error  VARCHAR(500)
);

-- A "partial index": only the NOT-sent rows are in it, so finding work stays fast
-- even when the table has millions of old, sent rows.
CREATE INDEX idx_outbox_event_unsent ON outbox_event (id) WHERE sent_at IS NULL;
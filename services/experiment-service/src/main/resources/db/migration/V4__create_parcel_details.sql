-- =====================================================================
-- V4__create_parcel_details.sql   (experiment-service, database: experiment_db)
--
-- parcel_details = the REAL parcels of past shifts at the terminal (one row = one parcel scan).
-- FlexSim simulates these parcels again, with the experiment's settings.
--
-- Same columns as the old app's table, so the old data files can be loaded unchanged
-- (scripts\import-parcel-data.ps1). The data is NOT part of this file: it is real company data
-- and never goes into Git.
--
-- This table is READ-ONLY for the application: rows come only from the import.
-- =====================================================================
CREATE TABLE parcel_details (
    id                            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    parcel_id                     VARCHAR(64),
    -- when the parcel arrived (date + time). The experiment's shift is matched on this.
    parcel_time_slot              TIMESTAMP(6),
    parcel_date                   DATE,
    parcel_timestamp              TIME,
    parcel_date_time              TIMESTAMP(6),
    -- the "operational day" of the shift (a night shift 23:00-06:30 keeps ONE date)
    parcel_edt_date               DATE,
    parcel_infeed_name            VARCHAR(50),
    -- where the parcel must go; can hold several values like '10440|10440|10440'
    sort_name                     VARCHAR(255),
    reject_code                   VARCHAR(50),
    parcel_weight                 DOUBLE PRECISION,
    parcel_length                 DOUBLE PRECISION,
    parcel_width                  DOUBLE PRECISION,
    parcel_height                 DOUBLE PRECISION,
    parcel_volume                 DOUBLE PRECISION,
    machine_sorting_direction     VARCHAR(50),
    additional_service_code_local VARCHAR(50),
    postal_code                   VARCHAR(20),
    service_code                  VARCHAR(20),
    sort_type                     VARCHAR(20),
    terminal_id                   INTEGER,
    -- kept only because the old data files contain it; the application calculates this itself
    flexsim_time_slot             INTEGER
);

-- FlexSim's question: "all parcels of THIS day between start and end" -> this index answers it fast.
CREATE INDEX idx_parcel_details_edt_date_time_slot ON parcel_details (parcel_edt_date, parcel_time_slot);

-- The screen's questions: "how many parcels / which sort names between start and end".
CREATE INDEX idx_parcel_details_time_slot ON parcel_details (parcel_time_slot);

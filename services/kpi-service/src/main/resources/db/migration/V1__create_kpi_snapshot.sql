-- =====================================================================
-- V1__create_kpi_snapshot.sql   (kpi-service, database: kpi_db)
--
-- ONE row = ONE KPI snapshot of a run, at one moment of the simulation ("tick").
--
-- Why ONE table with a JSON column (instead of the old 6 tables: chute, chute type, parcel,
-- conveyor, resource and infeed metrics)?
--   - React always reads a WHOLE snapshot, never one column alone.
--   - One insert per snapshot instead of hundreds (one row per chute before) -> much faster.
--   - FlexSim can add a new KPI later without a database change.
-- JSONB = PostgreSQL's binary JSON type: stored compact and can still be searched if needed.
-- =====================================================================
CREATE TABLE kpi_snapshot (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    -- the Kafka message id: the SAME snapshot delivered twice is saved only once
    event_id         VARCHAR(64)      NOT NULL,
    run_id           BIGINT,
    experiment_id    BIGINT           NOT NULL,
    -- seconds since the start of the simulation
    simulation_time  DOUBLE PRECISION NOT NULL,
    received_at      TIMESTAMP(6)     NOT NULL,
    -- the snapshot, already cleaned up (see KpiNormalizer)
    payload          JSONB            NOT NULL,
    CONSTRAINT uk_kpi_snapshot_event_id UNIQUE (event_id)
);

-- React's question: "all snapshots of THIS experiment, in time order" -> answered by this index.
CREATE INDEX idx_kpi_snapshot_experiment_time ON kpi_snapshot (experiment_id, simulation_time, id);
